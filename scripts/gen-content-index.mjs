// Generates src/i18n/contentIndex.js — a lightweight metadata index (title +
// intro per language) for every content item. List pages and site search only
// need this metadata, so keeping it separate lets the full item content
// (description / meaning / faq) be lazy-loaded per item in content.js instead
// of bundling all ~3.8 MB of JSON into the initial download.
//
// Runs automatically on `npm run dev` / `npm run build` (predev / prebuild) and
// can be run directly with `npm run gen:content`. The output file is committed
// so lint/build work without a prior generate step; regenerate after adding or
// editing item content.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const I18N_DIR = join(__dirname, "..", "src", "i18n");
const OUT_FILE = join(I18N_DIR, "contentIndex.js");

// Category folder names that hold per-item content (mirrors the glob in content.js).
const CATEGORIES = [
  "Chalisa", "Mantras", "Aartis", "Stotras", "Ashtakams",
  "Sahasranamas", "VratKathas", "Temples", "Festivals",
];

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return {};
  }
}

function listDirs(path) {
  try {
    return readdirSync(path).filter((name) => {
      try {
        return statSync(join(path, name)).isDirectory();
      } catch {
        return false;
      }
    });
  } catch {
    return [];
  }
}

const index = {};
let itemCount = 0;

for (const category of CATEGORIES) {
  const categoryDir = join(I18N_DIR, category);
  const slugs = listDirs(categoryDir).sort();
  if (slugs.length === 0) continue;

  const group = {};
  for (const slug of slugs) {
    const hi = readJson(join(categoryDir, slug, "hi.json"));
    const en = readJson(join(categoryDir, slug, "en.json"));
    group[slug] = {
      titleHi: hi.title || "",
      titleEn: en.title || "",
      introHi: hi.intro || "",
      introEn: en.intro || "",
    };
    itemCount++;
  }
  index[category] = group;
}

const banner = [
  "// AUTO-GENERATED by scripts/gen-content-index.mjs — do not edit by hand.",
  "// Lightweight per-item metadata (title + intro per language) for list pages",
  "// and site search. Full item content is lazy-loaded in content.js.",
  "// Regenerate with `npm run gen:content` (also runs on predev / prebuild).",
  "",
  "export default ",
].join("\n");

writeFileSync(OUT_FILE, banner + JSON.stringify(index, null, 2) + ";\n", "utf8");
console.log(`[gen-content-index] wrote ${itemCount} items across ${Object.keys(index).length} categories -> src/i18n/contentIndex.js`);
